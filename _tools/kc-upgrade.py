def slugify(title, old):
    base = re.sub(r'[^a-z0-9]+', '-', hashlib.md5(title.encode()).hexdigest()[:0] or '')
    # اسلاگ انگلیسی از کلمات لاتین عنوان؛ وگرنه از نام قدیمی
    latin = re.findall(r'[A-Za-z0-9]{2,}', title)
    if latin:
        s = '-'.join(latin[:5]).lower()
        return f'kc-{s}.html'
    return old  # نام hash قدیمی حفظ شود (کوتاه و یکتا)

def main():
    files = sorted(glob.glob(os.path.join(SRC, '*.html')))
    made, words_total, index_meta = 0, 0, []
    used = set()
    for f in files:
        src = open(f, encoding='utf-8', errors='ignore').read()
        title, desc, body = extract_meta(src)
        if not title: continue
        fam = fam_of(title)
        slug = slugify(title, os.path.basename(f))
        if slug in used:
            slug = slug.replace('.html', '') + '-' + hashlib.md5(title.encode()).hexdigest()[:6] + '.html'
        used.add(slug)
        out = render(slug, title, desc, body, fam)
        open(os.path.join(DST, slug), 'w', encoding='utf-8').write(out)
        txt = re.sub(r'<script[\s\S]*?</script>|<style[\s\S]*?</style>|<[^>]+>', ' ', out)
        w = len(txt.split())
        words_total += w
        made += 1
        index_meta.append({'t': title, 'u': slug, 'c': fam, 'cat': CAT_LB[fam], 'img': f'../assets/images/real/{IMG[fam]}', 'desc': (desc or title)[:160]})
    print(f'ساخته شد: {made} مقاله | میانگین کلمات: {words_total // max(made,1)}')
    json.dump(index_meta, open(os.path.join(ROOT, '_tools', 'kc-new-articles.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    # sitemap
    sm_path = os.path.join(ROOT, 'sitemap.xml')
    sm = open(sm_path, encoding='utf-8').read()
    added = 0
    entries = ''
    for m in index_meta:
        loc = f'https://pishtaj.ir/knowledge-center/{m["u"]}'
        if f'<loc>{loc}</loc>' not in sm:
            entries += f'  <url><loc>{loc}</loc><lastmod>2026-07-04</lastmod></url>\n'
            added += 1
    sm = sm.replace('</urlset>', entries + '</urlset>')
    open(sm_path, 'w', encoding='utf-8').write(sm)
    print(f'sitemap: +{added}')

if __name__ == '__main__':
    main()
