def build_block(slug, spec):
    parts = [MARK % slug]
    for s in spec["sections"]:
        parts.append(s)
    parts.append("<!-- /kc-enrich -->")
    return "\n".join(parts)


def insert_point(html_text):
    """محل تزریق: درست پس از معرفیِ موضوع و پیش از باکسِ CTA / بخش‌های قالبی."""
    m = re.search(r"(?is)<article\b", html_text)
    start = m.start() if m else 0
    # اولین h3ِ «نیاز به استعلام» بعد از شروع مقاله
    m3 = re.search(r"(?is)<h3[^>]*>[^<]*استعلام[^<]*</h3>", html_text[start:])
    if m3:
        return start + m3.start()
    # در غیر این صورت: پیش از دومین h2
    hs = [x.start() for x in re.finditer(r"(?i)<h2[\s>]", html_text[start:])]
    if len(hs) >= 2:
        return start + hs[1]
    return None


