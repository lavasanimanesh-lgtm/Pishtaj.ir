def build_block(slug, spec):
    """بلوکِ محتوا را می‌سازد.

    نکتهٔ ظاهری: نقطهٔ تزریق داخلِ باکسِ CTA است که `text-align:center` دارد.
    بدونِ این پوشش، متنِ فارسیِ مقاله وسط‌چین رندر می‌شد؛ بنابراین کلِ بلوک در
    یک لایهٔ راست‌چین پیچیده می‌شود.
    """
    parts = [MARK % slug]
    parts.append('<div class="kc-body" style="text-align:right">')
    for s in spec["sections"]:
        parts.append(s)
    parts.append("</div>")
    parts.append("<!-- /kc-enrich -->")
    return "\n".join(parts)


def insert_point(html_text):
    """محل تزریق: درست پس از معرفیِ موضوع و پیش از باکسِ CTA / بخش‌های قالبی."""
    m = re.search(r"(?is)<article\b", html_text)
    start = m.start() if m else 0
    # اولین h3ِ «نیاز به استعلام» بعد از شروع مقاله
    m3 = re.search(r"(?is)<h3[^>]*>[^<]*استعلام[^<]*</h3>", html_text[start:])
    if m3:
        return start + m3.start()
    # در غیر این صورت: پیش از دومین h2
    hs = [x.start() for x in re.finditer(r"(?i)<h2[\s>]", html_text[start:])]
    if len(hs) >= 2:
        return start + hs[1]
    return None


RE_TITLE = r"(<title>)[^<]*(</title>)"
RE_DESC = r'(<meta\s+name="description"\s+content=")[^"]*("\s*/?>)'


def head_inventory(html_text):
    """شمارش عناصر حساسِ head برای اطمینان از اینکه چیزی حذف نشود."""
    head = html_text.split("</head>")[0] if "</head>" in html_text else html_text[:6000]
    return {
        "canonical": len(re.findall(r'rel="canonical"', head)),
        "hreflang": len(re.findall(r'rel="alternate"', head)),
        "og": len(re.findall(r'property="og:', head)),
        "twitter": len(re.findall(r'name="twitter:', head)),
        "ldjson": len(re.findall(r'<script\s+type="application/ld\+json"', head)),
        "title": len(re.findall(r"<title>", head)),
        "desc": len(re.findall(r'name="description"', head)),
    }


def main():
    apply = "--apply" in sys.argv
    stats = {"title": 0, "desc": 0, "inject": 0, "replace": 0}
    problems = []

    for slug, spec in PAGES.items():
        path = os.path.join(KC, slug + ".html")
        if not os.path.exists(path):
            problems.append("صفحه پیدا نشد: %s" % slug)
            continue
        t = open(path, encoding="utf-8").read()
        orig = t
        before = head_inventory(t)

        # عنوان
        nt = re.sub(RE_TITLE,
                    lambda m: m.group(1) + H.escape(spec["title"], quote=False) + m.group(2), t, count=1)
        if nt != t:
            stats["title"] += 1
        t = nt

        # توضیح — الگو فقط تا نخستین " می‌خواند و هم "/> و هم "> را می‌پذیرد،
        # بنابراین نمی‌تواند از مرزِ تگ فراتر برود.
        if re.search(r'(?is)<meta\s+name="description"', t):
            nt = re.sub(RE_DESC,
                        lambda m: m.group(1) + H.escape(spec["desc"], quote=True) + m.group(2), t, count=1)
        else:
            nt = re.sub(r"(</title>)",
                        lambda m: m.group(1) + '\n<meta name="description" content="%s" />' % H.escape(spec["desc"], quote=True), t, count=1)
        if nt != t:
            stats["desc"] += 1
        t = nt

        # نگهبانِ ایمنی: head نباید چیزی را از دست بدهد
        after = head_inventory(t)
        lost = {k: (before[k], after[k]) for k in before if after[k] < before[k]}
        if lost:
            problems.append("%s: افتِ عنصر در head → %s" % (slug, lost))
            continue

        # تزریق
        block = build_block(slug, spec)
        exists = re.search(r"<!-- kc-enrich:%s -->.*?<!-- /kc-enrich -->" % re.escape(slug), t, re.S)
        if exists:
            t = t.replace(exists.group(0), block)
            stats["replace"] += 1
        else:
            pos = insert_point(t)
            if pos is None:
                problems.append("محل تزریق پیدا نشد: %s" % slug)
                continue
            t = t[:pos] + block + "\n" + t[pos:]
            stats["inject"] += 1

        if t != orig and apply:
            open(path, "w", encoding="utf-8").write(t)

        # سنجشِ حجمِ افزوده‌شده
        added = len(re.sub(r"<[^>]+>", "", block))
        print("%-34s +%5d کاراکتر متن  (%s)"
              % (slug, added, "جایگزینی" if exists else "تزریق"))

    print("-" * 70)
    print("عنوان: %d | توضیح: %d | تزریق جدید: %d | جایگزینی: %d"
          % (stats["title"], stats["desc"], stats["inject"], stats["replace"]))
    if problems:
        print("\n⚠️ ")
        for p in problems:
            print("   •", p)
    if not apply:
        print("\n(پیش‌نمایش — برای اجرا --apply بزنید)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
