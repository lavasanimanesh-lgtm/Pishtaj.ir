TH = '<th style="background:#f79400;color:#fff;padding:9px;border:1px solid #eee">%s</th>'
TD = '<td style="border:1px solid #e8e8ec;padding:8px;text-align:center">%s</td>'
TD_R = '<td style="border:1px solid #e8e8ec;padding:8px;text-align:right">%s</td>'


def table(headers, rows):
    h = "".join(TH % x for x in headers)
    body = ""
    for r in rows:
        body += "<tr>" + "".join((TD % c) if i == 0 else (TD_R % c)
                                 for i, c in enumerate(r)) + "</tr>"
    return ('<div style="overflow-x:auto"><table style="width:100%;'
            'border-collapse:collapse;font-size:14px">'
            '<thead><tr>' + h + '</tr></thead><tbody>' + body +
            '</tbody></table></div>')


def ul(items):
    return "<ul>" + "".join("<li>%s</li>" % i for i in items) + "</ul>"


def L(text, slug):
    """لینک داخلی به صفحه‌ای دیگر از مرکز دانش (تقویتِ گرافِ لینک)."""
    return '<a href="%s.html">%s</a>' % (slug, text)


def note(txt):
    return ('<p style="background:#fff8ec;border-right:4px solid #f79400;'
            'padding:10px 14px;font-size:14px"><b>نکته:</b> %s</p>' % txt)


def h2(title, body):
    return "<h2>%s</h2>\n%s\n" % (title, body)


def faq(items):
    out = ""
    for q, a in items:
        out += "<h3>%s</h3>\n<p>%s</p>\n" % (q, a)
    return h2("پرسش‌های متداول", out)


def rfq(items):
    return h2("چک‌لیست استعلام (RFQ)",
              "<p>برای اینکه قیمتِ دریافتی واقعاً قابل مقایسه باشد، این موارد را در "
              "استعلام قید کنید:</p>" + ul(items))


