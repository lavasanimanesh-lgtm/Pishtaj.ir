def segments(base_path):
    b = open(base_path, encoding='utf-8').read()
    s1 = b.find('<style>'); e1 = b.find('</style>', s1) + len('</style>')
    style1 = b[s1:e1]
    s2 = b.find('<style id="ptf-mobile-product-cta-style">'); e2 = b.find('</style>', s2) + len('</style>')
    style2 = b[s2:e2]
