def strip_filler_h2(html: str) -> tuple:
    """حذفِ بخش‌های قالبی (از <h2> تیترِ قالبی تا تیترِ بعدی یا پایان بلوک)."""
    removed = 0
    for head in FILLER_H2:
        pat = re.compile(
            r'<h2[^>]*>\s*' + re.escape(head) + r'\s*</h2>.*?(?=(?:<h2\b)|(?:<div style="background:linear-gradient\(135deg,#fffcf9))',
            re.S)
        html, k = pat.subn('', html)
        removed += k
    return html, removed


def inject_after_first_paragraph(html: str, content: str) -> str:
    m = re.search(r'</p>', html)
    if not m:
        return html + content
    return html[:m.end()] + content + html[m.end():]


def inject_before(html: str, marker: str, content: str) -> str:
    i = html.find(marker)
    if i == -1:
        return html + content
    return html[:i] + content + html[i:]


def process_nace(apply: bool):
    p = os.path.join(ROOT, 'knowledge-center/nace-mr0175-sour-service-guide.html')
    s = open(p, encoding='utf-8').read()
    orig = s
    s, removed = strip_filler_h2(s)
    s = inject_after_first_paragraph(s, NACE_CONTENT)
    s = s.replace('<title>راهنمای استاندارد NACE MR0175 | پیشرو تجهیز فرتاک</title>',
                  '<title>NACE MR0175 و سرویس اسیدی؛ راهنمای انتخاب لوله و فلنج</title>', 1)
    if apply:
        open(p, 'w', encoding='utf-8').write(s)
    print('nace-mr0175: %d بخش قالبی حذف شد، %d کاراکتر محتوای جدید (%s)'
          % (removed, len(NACE_CONTENT), 'اعمال شد' if apply else 'پیش‌نمایش'))
    return s != orig


