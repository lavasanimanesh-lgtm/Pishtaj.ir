def inject_css(h: str) -> str:
    if ".deep-table" in h:
        return h
    return h.replace("</style>", TABLE_CSS + "</style>", 1)


def already_upgraded(h: str, marker: str) -> bool:
    return f'data-deep-section="{marker}"' in h


def upgrade(path: str, html_block: str) -> bool:
    h = open(path, encoding="utf-8").read()
    marker = re.search(r'data-deep-section="([^"]+)"', html_block).group(1)
    if already_upgraded(h, marker):
        print(f"  = {path}: already has section '{marker}' (skip)")
        return True
    h = inject_css(h)
    m = re.search(r"<h2>[^<]*راهنماهای مرتبط[^<]*</h2>", h)
    if not m:
        print(f"  !! no marker <h2>راهنماهای مرتبط</h2> in {path}")
        return False
    h = h.replace(m.group(0), html_block + "\n" + m.group(0), 1)
    open(path, "w", encoding="utf-8").write(h)
    print(f"  + {path}: injected deep section '{marker}'")
    return True


def main():
    ok = True
    for fn, block in PAGES.items():
        p = os.path.join("suppliers", fn)
        if not os.path.exists(p):
            print(f"  !! missing: {p}")
            ok = False
            continue
        if not upgrade(p, block):
            ok = False
    if not ok:
        sys.exit(1)
    print("done")


if __name__ == "__main__":
    main()
